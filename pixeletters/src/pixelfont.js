// Get pixel grid for a full word
function getWordPixels(word) {
  const letters = word.toUpperCase().split('');
  const grids = letters.map(ch => PIXEL_FONT[ch] || PIXEL_FONT['A']);

  // Each letter is 5 wide, 1 pixel gap between letters
  const totalWidth = letters.length * 5 + (letters.length - 1);
  const height = 7;

  const combined = [];
  for (let row = 0; row < height; row++) {
    const line = [];
    for (let i = 0; i < letters.length; i++) {
      if (i > 0) line.push(0); // gap
      for (let col = 0; col < 5; col++) {
        line.push(grids[i][row][col]);
      }
    }
    combined.push(line);
  }

  return { grid: combined, width: totalWidth, height, letterWidth: 5, gap: 1 };
}

// Get which letter index a column belongs to
function getLetterIndex(col, letterCount) {
  const stride = 6; // 5 pixels + 1 gap
  const letterIdx = Math.floor(col / stride);
  const localCol = col % stride;
  if (localCol === 5) return -1; // gap column
  if (letterIdx >= letterCount) return -1;
  return letterIdx;
}

