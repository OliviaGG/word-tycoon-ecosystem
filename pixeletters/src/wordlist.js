// Active word lists (populated by init, falls back to built-in)
const targets = {};    // { length: [WORD, ...] }
const dictionary = {}; // { length: [WORD, ...] }

function sleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function init() {
  const MAX_RETRIES = 5;
  const RETRY_DELAY = 3000;
  let fetched = false;

  for (let attempt = 1; attempt <= MAX_RETRIES; attempt++) {
    try {
      console.log(`[WordList] Fetching from Word Bank (attempt ${attempt}/${MAX_RETRIES})...`);

      // Fetch all targets
      const targetsRes = await fetch(`${WORD_BANK_URL}/targets`);
      if (!targetsRes.ok) throw new Error(`Targets fetch failed: ${targetsRes.status}`);
      const targetsData = await targetsRes.json();

      // Store targets by length (uppercase)
        for (const [len, words] of Object.entries(targetsData)) {
          const length = parseInt(len);
          targets[length] = words.map(w => w.toUpperCase());
        }

      // Fetch dictionary for each length we have targets for
      const lengths = Object.keys(targets).map(Number);
      for (const len of lengths) {
        try {
          const dictRes = await fetch(`${WORD_BANK_URL}/dictionary/${len}`);
          if (dictRes.ok) {
            const dictWords = await dictRes.json();
              dictionary[len] = dictWords.map(w => w.toUpperCase());
          }
        } catch (e) {
          // Dictionary fetch for this length failed, targets still usable
          console.log(`[WordList] Dictionary fetch failed for length ${len}, using targets as dictionary`);
        }
      }

      const totalTargets = Object.values(targets).reduce((sum, arr) => sum + arr.length, 0);
      const totalDict = Object.values(dictionary).reduce((sum, arr) => sum + arr.length, 0);
      console.log(`[WordList] Loaded ${totalTargets} targets and ${totalDict} dictionary words from Word Bank`);
      fetched = true;
      break;
    } catch (err) {
      console.log(`[WordList] Word Bank fetch failed (attempt ${attempt}/${MAX_RETRIES}): ${err.message}`);
      if (attempt < MAX_RETRIES) {
        console.log(`[WordList] Retrying in ${RETRY_DELAY / 1000}s...`);
        await sleep(RETRY_DELAY);
      }
    }
  }

  if (!fetched) {
    console.log('[WordList] Using built-in fallback word lists');
      for (const [len, words] of Object.entries(BUILTIN_WORDS)) {
        const length = parseInt(len);
        targets[length] = [...words];
        dictionary[length] = [...words];
      }
  }
}

function getTargets(length) {
  return targets[length] || [];
}

function getDictionary(length) {
  return dictionary[length] || targets[length] || [];
}

function getRandomWord(length) {
  const list = targets[length];
  if (!list || list.length === 0) return null;
  return list[Math.floor(Math.random() * list.length)];
}

function isValidWord(word) {
  const upper = word.toUpperCase();
  const list = targets[upper.length] || [];
  return list.includes(upper);
}

function isValidGuess(word) {
  const upper = word.toUpperCase();
  const len = upper.length;
  const dict = dictionary[len] || targets[len] || [];
  return dict.includes(upper) || (targets[len] || []).includes(upper);
}

module.exports = { init, getRandomWord, isValidWord, isValidGuess, getTargets, getDictionary };
